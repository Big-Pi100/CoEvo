// CoEvo · App 元信息（版本号等）
//
// 🔴 **版本号出现在两处，必须一致**
// | 位置 | 用途 |
// |---|---|
// | `pubspec.yaml` 的 `version:` | **构建系统用**（iOS `CFBundleShortVersionString` / Android `versionName` 的来源） |
// | 本文件的 [kCoEvoVersion] | **界面显示用**（「关于」页 / 「我的」页副标题） |
//
// ⚠️ **为什么不直接读 pubspec**：那需要 `package_info_plus`（一个新的第三方依赖），
//    而这里只需要一个字符串 → 为它引入依赖不划算。
// 🔑 代价是**两处会漂** → 用
//    `scripts/query_verify/bin/verify_app_version.dart` 做守护断言
//    （解析 pubspec 与本文件，要求一致）。**"注释里提醒"不算防线，脚本才算。**
//
// 口径（本项目既有约定）：**`x.y.z` 是界面唯一可见的版本号**；
// `pubspec` 里 `+` 之后的 `N`（build number）只给构建系统用，**不在界面显示**
// （两段含义不同，混着显示会让用户困惑「为什么有两个版本」）。

/// 界面显示的版本号（= `pubspec.yaml` 的 `version:` 中 `+` **之前**的部分）。
///
/// ⚠️ 改这里必须同步改 `pubspec.yaml`（反之亦然）—— 有脚本守着，漂了会红。
const String kCoEvoVersion = '1.0.0';

/// App 显示名（「关于」页用）。
///
/// 🔴 **2026-10-12 白哥定案：产品名从「记忆之书」改为「记忆笔记」**（**ICP 备案要求**）。
///    原因：「记忆之**书**」的「书」触发备案的**前置审批字眼规则** ——
///    腾讯云官方原文：「App 名称若包含 新闻、**出版**、教育、医疗保健… 等**字眼**或
///    **明显属于此类字眼**的，需提供对应主管部门下发的前置审批文件」。
///    ⇒ 改「记忆**笔记**」避开「出版」；备案「应用类型」同时选「**生活-工具**」（避开教育）。
///
/// ⚠️ 改名**不是一处字符串**，而是一组动作（本项目已有判据）。当前 5 处载体：
/// | # | 载体 | 值 |
/// |---|---|---|
/// | 1 | 本常量（「关于」页「应用名称」那行）| `记忆笔记` |
/// | 2 | iOS `Info.plist` 的 `CFBundleDisplayName` | `记忆笔记` |
/// | 3 | Android `AndroidManifest.xml` 的 `android:label` | `记忆笔记` |
/// | 4 | **ASC 里的 App 名称 + 订阅产品本地化名** | ⏳ 白哥在网页改 |
/// | 5 | **ICP 备案里的 APP 名称** | ⏳ 白哥在备案系统改 |
///
/// 🔴🔴 **备案的两条硬约束**（这就是「为什么 2 必须跟 4/5 一起改」的依据）：
/// · **备案名 = 手机上图标下方的名称** —— 腾讯云官方 FAQ 原话：
///   「APP 名称应填写安装在手机或终端上后，**公众能直接看到的 APP 图标下方显示的名称**」；
///   且「若**安装后显示的名称改变**，则应该进行**备案变更**」。
/// · **ASC 后台填的 App 名称必须与备案名逐字一致** —— Apple 已开**强校验**：
///   名称不符时报「App名称与App备案信息不相符」⇒ **无法储存、无法提审**。
///   （实测结论：Apple **不校验包里的名称**，只校验 iTC 后台填的那个 ——
///    但**管局会核图标下的名称**，所以载体 2 同样不能偷懒。）
///
/// 🔑 判据：**改名是一组动作，不是一处字符串** —— 漏一处就会出现
///    「App 叫记忆笔记、订阅叫记忆之书 专业版」这种割裂（Apple 审核也会挑）。
/// 📌 `Bundle ID`（`com.coevo.coevoApp`）与 `Product ID` **不改** —— 它们是技术标识，
///    改了要重建证书/描述文件/IAP 产品（**且 Product ID 一旦用过即不可复用**），
///    与显示名无关。
///
/// 📜 沿革：`CoEvo`（至 2026-10-11）→ `记忆之书`（10-11）→ **`记忆笔记`（10-12）**。
const String kCoEvoName = '记忆笔记';
