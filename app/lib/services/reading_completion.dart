// CoEvo · 「读完一篇文章」的判定 —— **纯逻辑，无 Flutter 依赖**
//
// 🔴 为什么单独一个文件、且**不得 import 任何 Flutter 包**：
//   本机 `flutter` 必崩（管道耗尽）→ 只有**纯 Dart** 才能在本地独立验证。
//   同 `services/fsrs_service.dart` / `services/spelling_grader.dart` 的做法。
//   → 判定逻辑单独一个文件，就能用 `scripts/query_verify/bin/verify_reading_completion.dart`
//     把**每一条边界**都锁住，而不是只能靠「在真机上滑一下看看」。
//
// # 口径来源（白哥 2026-09-29 定「乙」）
// 📄 `docs/design/profile-redesign-plan-2026-09-29.md` §七
// > 「乙　**读完**的文章数（滚到底 / 停留 ≥ 阈值）」
//
// # 🔴 为什么是**两个**条件相乘，而不是「滚到底」一个
//
// 「滚到底」单独用会**大面积误判**：
// | 场景 | 只判「滚到底」的结果 | 实际 |
// |---|---|---|
// | **文章短于一屏**（`maxScrollExtent == 0`） | `extentAfter` **恒为 0** → 一进页就「读完」 | 可能只是点开扫了一眼 |
// | 滑到底部**立刻退出** | 到底那一刻就「读完」 | 多半是在找别的东西 |
//
// → 加**最短停留** `minDwell`，把「到底但没读」排除。
//   🔑 它**不是保险，是必须的** —— 上面第一种场景在短文章上是**必然发生**的。
//
// # ⚠️ 本判定的**已知取舍**（如实标注，不假装完美）
//
// | 情况 | 判定 | 是否可接受 |
// |---|---|---|
// | 长文只读前半（停留很久但没滚到底） | **不算**读完 | ✅ 有意 —— 「读完」就该是读完，不给它注水 |
// | 短文章认真读完（一屏到底，停留够） | 算 | ✅ 正确 |
// | 快速滑到底、正好停留 ≥3s | 算 | 🟠 可能没真读，但**无更可靠的端侧信号**（滚动速率/可见时长都需埋点，属过度设计） |
//
// 🔑 后者若要更准，需要「按段落记可见时长」—— 那是另一个量级的复杂度，
//    而「阅读篇数」只是展示型统计，不值得。**取舍写在这里，避免将来被当成 bug。**

/// 「到底」的容差（像素）。
///
/// 为什么不是**严格 `== 0`**：用户滚到底后常因惯性/回弹停在离底几像素处；
/// 严格 0 会让「明明读到底了却不算」——**漏判**比误判更难被发现（用户只会觉得数字不对）。
///
/// ⚠️ 取值 24 ≈ 一行正文的高度（正文 17px × 行高 ≈ 1.7 → ~29px，取略小）。
/// **不该调大**：超过一屏的 5% 就变成「没到底也算到底」。
const double kReadBottomThresholdPx = 24.0;

/// 最短停留时长。
///
/// 🔑 存在的**唯一**理由见文件头：短文章的 `extentAfter` 恒为 0。
/// 3s 的取值：短到「点开就退」不会满足，又不至于让认真读的人等太久才记上。
const Duration kReadMinDwell = Duration(seconds: 3);

/// 是否算「读完」。
///
/// - [extentAfter]：`ScrollPosition.extentAfter`（**离底部还有多少像素**）
/// - [dwell]：从**进入阅读页**到此刻的停留时长
///
/// ⚠️ 调用方（阅读页）负责处理「布局还没完成」的情况
/// （`ScrollController.hasClients == false`）——那种情况下**不要**调本函数，
/// 因为它无法区分「内容真的不足一屏」与「还没量出来」，而两者结论相反。
bool isArticleCompleted({
  required double extentAfter,
  required Duration dwell,
}) {
  return extentAfter <= kReadBottomThresholdPx && dwell >= kReadMinDwell;
}
