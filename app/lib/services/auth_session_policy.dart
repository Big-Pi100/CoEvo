/// 从本地已存的「登录标识」里取回邮箱 —— **只用于服务端没能回答时的兜底**。
///
/// # 为什么需要
///
/// `verifyToken` 在**网络失败 / 非 200** 时返回 `{'valid': true}`（**刻意宽容**：
/// 不该因为一次网络抖动就把用户登出），但它**带不回 `email`**。
/// 而 `email` 的用途是判断「**这个账号是否已完成注册**」⇒ 缺了它，
/// 已注册账号会被判成「未注册」（界面少显示一次邮箱，订阅覆盖层也会误放行）。
///
/// 🔑 兜底数据**本来就在本地**：`_usernameKey` 存的就是登录标识，
///    且自 2026-09-29 起注册 / 登录都以**邮箱**为标识。
///
/// ⚠️ **必须判 `@`**：**存量**匿名账号（`trial_*`，该机制 2026-10-09 已删）
///    存的标识不是邮箱。若无脑回填，它们会被误判成「**已注册**」——
///    那是**反方向**的错，比原 bug 更隐蔽。
///    无法判定时**返回 `null`**（= 保持「未注册」）是安全的一侧：
///    最坏结果只是界面少显示一次邮箱，不会误判账号类型。
String? emailFromStoredLoginId(String? loginId) {
  final v = loginId?.trim();
  if (v == null || v.isEmpty) return null;
  return v.contains('@') ? v : null;
}
