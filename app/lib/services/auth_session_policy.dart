/// # 🔴 为什么单独放一个文件
///
/// [emailFromStoredLoginId] 是一条「**兜底换算**」—— 它错了不会报错，
/// 只会让「这个账号算不算已注册」判错。而它的输入空间很小 ⇒ 可以**穷举**。
///
/// 🔑 所以把它抽成纯函数，让 `scripts/query_verify/bin/verify_auth_entry.dart`
///    能直接 `import` 并跑真值表 —— 比「在界面代码里做文本匹配」强得多。
///    📌 同族先例：`achievement_rules.dart` / `article_text.dart` 都是这样被离线穷举的。
///
/// ⚠️ **本文件不得 import Flutter**（`query_verify` 是纯 Dart 运行时）。
///    一旦引入 `package:flutter/*`，那套断言会直接编译不过。
///
/// # 🔴 2026-10-09：删掉了 `shouldPromptLoginOnLaunch`
///
/// 它决定「启动时要不要弹登录引导」，判据是 `!isAuthenticated && trialUsed`。
/// 随**试用账号机制整体退役**（白哥：「不需要试用账号，未登录本来就可以直接用」）
/// ⇒ 它的两个输入都失去了意义：
/// · `trialUsed` = 「本机试用名额用没用过」—— 不再有试用名额；
/// · 于是「未登录」**不该**被拦一道弹窗 —— 未登录是**一等状态**，直接用就是。
/// ⇒ **启动时不再有任何自动弹窗**；登录入口是「我的」页账号组的常驻入口。
/// 📄 `docs/review/trial-account-removal-2026-10-09.md`
